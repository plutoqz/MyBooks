def knowledge_table(filename, title, headers, rows, widths, subtitle="",
                    source_note="资料：本节正文及节末参考文献。"):
    setup()
    row_lines = []
    for row in rows:
        row_lines.append([
            wrap_text(str(text), (684 * width - 20) / 9.5 * 0.90)
            for text, width in zip(row, widths)
        ])
    heights = [max(len(text.splitlines()) for text in row) * 15 + 17
               for row in row_lines]
    height_pt = sum(heights) + 156
    fig, ax = plt.subplots(figsize=(10, height_pt / 72))
    fig.subplots_adjust(left=0.025, right=0.975, bottom=36 / height_pt,
                        top=1 - 90 / height_pt)
    ax.set_xlim(0, 1)
    ax.set_ylim(0, sum(heights) + 30)
    ax.axis("off")
    x_positions = np.cumsum([0] + list(widths))
    top = sum(heights) + 30
    ax.axhspan(top - 27, top, color="#E8EEF1", linewidth=0)
    for x, header in zip(x_positions, headers):
        ax.text(x + 0.012, top - 8, header, fontsize=10, weight="bold", va="top",
                color="#25343A")
    cursor = top - 29
    for i, (row, row_height) in enumerate(zip(row_lines, heights)):
        if i % 2 == 0:
            ax.axhspan(cursor - row_height, cursor, color="#F6F8F9", linewidth=0)
        for x, text in zip(x_positions, row):
            ax.text(x + 0.012, cursor - 8, text, fontsize=9.5, va="top",
                    color="#25343A", linespacing=1.45)
        cursor -= row_height
    fig.text(0.025, 0.98, title, fontsize=15, weight="bold")
    if subtitle:
        fig.text(0.025, 0.93, subtitle, fontsize=9)
    fig.text(0.025, 0.015, source_note, fontsize=8)
    save_volume_figure(fig, Path(FIGURES) / filename)
    plt.close(fig)



def rail_corridors():
    setup()
    years = list(range(2017, 2025))
    teu = [3382, 53425, 94000, 230000, 610000, 756000, 860000, 960000]
    fig, (ax, table) = plt.subplots(2, 1, figsize=(10, 8))
    positions = np.arange(len(years))
    bars = ax.bar(positions, np.array(teu) / 10000, color="#287C80", width=0.6)
    for bar, value in zip(bars, teu):
        ax.text(bar.get_x() + 0.3, bar.get_height() + 2,
                f"{value / 10000:.2f}", ha="center", fontsize=9)
    ax.set_xticks(positions, [str(year) for year in years])
    ax.set_ylim(0, 112)
    ax.set_ylabel("铁海联运班列运量（万标箱）")
    ax.set_title("西部陆海新通道铁海联运（2017—2024 年）", fontsize=11)
    ax.spines[["top", "right"]].set_visible(False)
    ax.grid(axis="y", color="#DFE5E8")
    ax.set_axisbelow(True)
